import logging
import re
from typing import List, Dict, Optional, Any
from sqlalchemy.orm import Session

from backend.app.db.models import GitHubConnectionModel, ProposalModel
from backend.app.github.client import GitHubClient, GitHubNotFoundError, GitHubError
from backend.app.github.schemas import GitHubCommitItem

logger = logging.getLogger("coframe.github.commits")


def format_commit_message(proposal: ProposalModel, decided_by: str) -> str:
    """Formats standardized commit message: feat(coframe): {proposal_summary}"""
    clean_summary = proposal.summary.strip().rstrip(".")
    msg = f"""feat(coframe): {clean_summary}

Proposal ID: {proposal.id}
Agent: {proposal.agent_id.upper()}
Approved by: {decided_by.capitalize()}
Context Version: v{proposal.base_context_version}
Artifact Version: v{proposal.base_artifact_version + 1}

Reasoning:
{proposal.reasoning}

Exported via COFRAME Multiplayer Workspace.
"""
    return msg


def parse_coframe_commit(commit_message: str) -> Optional[Dict[str, str]]:
    """Detects if commit was generated by COFRAME and extracts metadata."""
    if "feat(coframe)" in commit_message or "COFRAME" in commit_message:
        prop_match = re.search(r"Proposal ID:\s*([a-zA-Z0-9_-]+)", commit_message)
        agent_match = re.search(r"Agent:\s*([a-zA-Z0-9_-]+)", commit_message)
        return {
            "proposal_id": prop_match.group(1) if prop_match else None,
            "agent_id": agent_match.group(1) if agent_match else None,
        }
    return None


class CommitService:
    def __init__(self, db: Session, client: Optional[GitHubClient] = None):
        self.db = db
        self.client = client or GitHubClient()

    async def list_commits(self, project_id: str, branch: Optional[str] = None) -> List[GitHubCommitItem]:
        """Lists commits from the connected repository, identifying COFRAME contributions."""
        conn = (
            self.db.query(GitHubConnectionModel)
            .filter(GitHubConnectionModel.project_id == project_id)
            .first()
        )
        if not conn:
            raise GitHubNotFoundError("No repository connected to this project.")

        commits_raw = await self.client.list_commits(conn.owner, conn.repository_name, sha=branch)
        result: List[GitHubCommitItem] = []

        for c in commits_raw:
            sha = c.get("sha", "")
            commit_obj = c.get("commit", {})
            msg = commit_obj.get("message", "")
            author_obj = commit_obj.get("author", {})
            author_name = author_obj.get("name", "Unknown")
            author_date = author_obj.get("date", "")
            html_url = c.get("html_url", f"{conn.repository_url}/commit/{sha}")

            parsed = parse_coframe_commit(msg)
            is_coframe = parsed is not None
            related_proposal_id = parsed["proposal_id"] if parsed else None
            actor_identity = parsed["agent_id"] if parsed else None

            # First line of commit message for card display
            first_line = msg.split("\n")[0]

            result.append(
                GitHubCommitItem(
                    sha=sha,
                    message=first_line,
                    author_name=author_name,
                    author_date=author_date,
                    html_url=html_url,
                    is_coframe_commit=is_coframe,
                    related_proposal_id=related_proposal_id,
                    actor_identity=actor_identity,
                )
            )

        return result

    async def create_atomic_commit(
        self,
        project_id: str,
        branch_name: str,
        files: Dict[str, str],
        commit_message: str,
    ) -> str:
        """
        Creates a single atomic commit containing all exported files using GitHub Git Database API:
        1. Create blobs for each file.
        2. Create a git tree referencing the blobs.
        3. Create a commit pointing to the tree with the branch HEAD as parent.
        4. Advance the branch ref to the new commit SHA.
        """
        conn = (
            self.db.query(GitHubConnectionModel)
            .filter(GitHubConnectionModel.project_id == project_id)
            .first()
        )
        if not conn:
            raise GitHubNotFoundError("No repository connected to this project.")

        owner = conn.owner
        repo = conn.repository_name

        # 1. Get current branch HEAD commit SHA
        branch_info = await self.client.get_branch(owner, repo, branch_name)
        base_commit_sha = branch_info["commit"]["sha"]
        base_tree_sha = branch_info["commit"]["commit"]["tree"]["sha"]

        # 2. Create blobs for all exported files
        tree_items = []
        for path, content in files.items():
            blob_resp = await self.client.create_blob(owner, repo, content)
            tree_items.append({
                "path": path,
                "mode": "100644",
                "type": "blob",
                "sha": blob_resp["sha"],
            })

        # 3. Create tree
        tree_resp = await self.client.create_tree(owner, repo, base_tree=base_tree_sha, tree_items=tree_items)
        new_tree_sha = tree_resp["sha"]

        # 4. Create commit
        commit_resp = await self.client.create_commit(
            owner=owner,
            repo=repo,
            message=commit_message,
            tree_sha=new_tree_sha,
            parents=[base_commit_sha],
        )
        new_commit_sha = commit_resp["sha"]

        # 5. Update branch reference
        await self.client.update_ref(
            owner=owner,
            repo=repo,
            ref=f"refs/heads/{branch_name}",
            sha=new_commit_sha,
            force=False,
        )

        logger.info(f"Created atomic commit {new_commit_sha[:7]} on branch '{branch_name}'.")
        return new_commit_sha
